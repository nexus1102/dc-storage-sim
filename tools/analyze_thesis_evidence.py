"""Bounded paper analysis of existing sealed experiments and external measurements.
No simulation, solver call or parameter/default mutation. Figures go to results/.
"""
from pathlib import Path
import json
import hashlib
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

ROOT=Path(__file__).resolve().parents[1]


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def analyze():
    delivery=json.loads((ROOT/'docs/research/delivery/acceptance_evidence.json').read_text(encoding='utf-8'))
    main=ROOT/delivery['run'];matched=ROOT/delivery['matched_reference_audit']['run']
    for folder,expected in [(main,delivery['seal_sha256']),(matched,delivery['matched_reference_audit']['seal_sha256'])]:
        if digest(folder/'SEAL.json')!=expected:raise ValueError('changed experiment seal')
        seal=json.loads((folder/'SEAL.json').read_text(encoding='utf-8'))
        for record in seal['files']:
            if digest(folder/record['path'])!=record['sha256']:raise ValueError('changed sealed file: '+record['path'])
    for name,expected in delivery['model_source_sha256'].items():
        if digest(ROOT/'sim'/name)!=expected:raise ValueError('changed simulation core: '+name)
    calibration=json.loads((ROOT/'docs/research/calibration/external_calibration_evidence.json').read_text(encoding='utf-8'))
    for record in calibration['curated_files']:
        if digest(ROOT/record['path'])!=record['sha256']:raise ValueError('changed measured derivative')
    factorial=pd.read_csv(main/'factorial.csv');capacity=pd.read_csv(matched/'matched_capability.csv')
    interaction=[]
    for arch,group in factorial.groupby('arch',sort=False):
        values=group.set_index('arm');c=values.cost
        # Difference of cost savings; lo/hi propagate solver bounds, not confidence.
        signs={'sequential_reg':1,'joint_reg':-1,'sequential_no_reg':-1,'joint_no_reg':1}
        low=sum(s*values.loc[k,'lo' if s>0 else 'hi'] for k,s in signs.items())
        high=sum(s*values.loc[k,'hi' if s>0 else 'lo'] for k,s in signs.items())
        interaction.append(dict(architecture=arch,interaction_yuan=sum(signs[k]*c[k] for k in signs),
            solver_lower_yuan=float(low),solver_upper_yuan=float(high),
            total_cost_reduction_yuan=float(c['sequential_no_reg']-c['joint_reg']),
            total_cost_reduction_percent=float(100*(1-c['joint_reg']/c['sequential_no_reg']))))
    battery=capacity[capacity['mode']=='battery_only'];joint=capacity[capacity['mode']=='joint']
    combined=battery.merge(joint,on=['arch','duration_h'],suffixes=('_battery','_joint'))
    combined['increment_mw']=combined.power_mw_joint-combined.power_mw_battery
    if len(combined)!=8 or (combined.increment_mw < -1e-6).any():raise AssertionError('capability pairing inconsistent')
    sources=[main/'factorial.csv',matched/'matched_capability.csv',main/'design_faults.csv']
    report=dict(date='2026-11-11',scope='existing representative-day synthetic-contract mechanisms plus external priors; no new experiments',
        simulator_source_unchanged=True,default_adoption=False,standard_compliance='BLOCKED',
        sources=[dict(path=p.relative_to(ROOT).as_posix(),sha256=digest(p)) for p in sources],
        seals={main.name:digest(main/'SEAL.json'),matched.name:digest(matched/'SEAL.json')},
        factorial=interaction,matched_capacity=combined[['arch','duration_h','power_mw_battery','power_mw_joint','increment_mw']].to_dict('records'),
        scientific_limits=['single historical price representative day','different installed assets across architectures',
            'joint capacity censored by reference import ceiling','synthetic service contracts and uncalibrated target site',
            'solver bounds are not statistical confidence intervals','no engineering/Tier certification'])
    folder=ROOT/'docs/research/analysis';folder.mkdir(parents=True,exist_ok=True)
    (folder/'paper_analysis_evidence.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')
    # Shareable scientific figure; no fonts, labels or images generated by AI.
    cells=pd.read_csv(ROOT/'data/empirical/20261111/hust_two_cells.csv')
    arrivals=pd.read_csv(ROOT/'data/empirical/20261111/azure_code_2024_minute.csv')
    fit=calibration['battery']['fit'];fig,axes=plt.subplots(1,2,figsize=(12,4.4),layout='constrained')
    for cell,color in [('1-1','#176b95'),('1-2','#ba5b24')]:
        d=cells[cells.cell==cell];axes[0].plot(d.observed_dc_wh_efc,d.relative_capacity_retention,color=color,lw=1,label=f'Cell {cell}')
    x=np.linspace(0,cells.observed_dc_wh_efc.max(),300)
    axes[0].plot(x,fit['intercept']-fit['loss_per_observed_dc_wh_efc']*x,'k--',lw=1,label='Fit: 1-1 cycles 11-902')
    cut=cells[(cells.cell=='1-1')&(cells.cycle==902)].observed_dc_wh_efc.iloc[0]
    axes[0].axvline(cut,color='gray',ls=':',lw=1)
    axes[0].set(xlabel='Recorded DC nominal-Wh EFC',ylabel='Capacity / initial 10-cycle median',title='LFP cell prior: holdout and transfer limits')
    axes[0].legend(fontsize=8)
    arrivals['minute']=pd.to_datetime(arrivals.minute,utc=True)
    full=arrivals[arrivals.complete_minute].set_index('minute')
    rate=full.requests.resample('15min').sum()/full.requests.resample('15min').count()/60
    axes[1].plot(rate.index,rate.to_numpy(),color='#176b95',lw=.8,label='15-min mean of observed minute rates')
    split=calibration['arrivals']['code_2024']['train_minutes']
    axes[1].axvline(full.index[split],color='gray',ls=':',label='Chronological holdout begins')
    axes[1].set(xlabel='UTC, May 2024',ylabel='Requests/s',title='Azure code: seven days of production arrivals')
    axes[1].tick_params(axis='x',rotation=25);axes[1].legend(fontsize=8)
    for ax in axes:ax.grid(alpha=.18)
    out=ROOT/'results/paper_analysis';out.mkdir(parents=True,exist_ok=True)
    fig.savefig(out/'external_measurement_limits.png',dpi=180)
    fig.savefig(out/'external_measurement_limits.svg',metadata={'Date':None});plt.close(fig)
    print(json.dumps(interaction,indent=2))
    print('Paper evidence and two-panel scientific figure saved; no simulation run')
    return report


if __name__=='__main__':analyze()
